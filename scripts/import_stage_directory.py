def _code(value) -> str | None:
    if value is None:
        return None
    if isinstance(value, dt.datetime):
        # Excel превратил «10.1» в 10 января: день — раздел, месяц — номер работы.
        return f"{value.day}.{value.month}"
    text = str(value).strip().rstrip(".")
    return text or None


def read_rows() -> list[dict]:
    import openpyxl

    sheet = openpyxl.load_workbook(SOURCE, data_only=True).active
    rows, parent = [], None
    for index, values in enumerate(sheet.iter_rows(min_row=4, values_only=True), start=4):
        if not values or values[1] is None:
            continue
        code = _code(values[0])
        name = str(values[1]).strip()
        types = [OBJECT_TYPES[i] for i in range(9) if values[2 + i]]
        if code in SECTION_CODES:
            parent = None
            continue
        if code:
            parent = code
        rows.append({"row": index, "code": code, "parent": None if code else parent, "name": name,
                     "types": types})
    return rows


def build() -> dict:
    rows = read_rows()
    owner: dict[int, str] = {}

    def claim(row, stage_code):
        if row["row"] in owner:
            raise SystemExit(f"Строка {row['row']} ({row['name']}) попала в {owner[row['row']]} и {stage_code}")
        owner[row["row"]] = stage_code

    # сначала явные подстроки, затем строки с номером вместе с оставшимися подстроками
    for stage in STAGES:
        for selector in stage["rows"]:
            if isinstance(selector, tuple):
                parent, name = selector
                found = [r for r in rows if r["parent"] == parent and r["name"] == name]
                if not found:
                    raise SystemExit(f"Нет подстроки {selector} для {stage['code']}")
                for r in found:
                    claim(r, stage["code"])
    for stage in STAGES:
        for selector in stage["rows"]:
            if isinstance(selector, tuple):
                continue
            found = [r for r in rows if r["code"] == selector]
            if not found:
                raise SystemExit(f"Нет строки {selector} для {stage['code']}")
            claim(found[0], stage["code"])
            for r in rows:
                if r["parent"] == selector and r["row"] not in owner:
                    claim(r, stage["code"])

    missing = [r for r in rows if r["row"] not in owner]
    if missing:
        raise SystemExit("Строки без этапа: " + "; ".join(f"{r['row']} {r['name']}" for r in missing))

    result = []
    for stage in STAGES:
        covered = [r for r in rows if owner[r["row"]] == stage["code"]]
        # Применимость — объединение отметок всех строк этапа; exclude_types правит явные
        # несостыковки Excel (например, «пирог кровли» отмечен и для дорог).
        types = [t for t in OBJECT_TYPES if any(t in r["types"] for r in covered)
                 and t not in stage.get("exclude_types", ())]
        observability = stage["obs"]
        method = stage.get("method") or ("inspection" if observability == "no" else "cameras")
        profile = stage.get("profile") or {}
        if method == "cameras" and not profile.get("strong_signs"):
            raise SystemExit(f"У этапа {stage['code']} по камерам нет профиля")
        section_key = stage["code"].split("-")[0]
        section_key = ".".join(section_key.split(".")[:2]) if section_key.startswith("12") else "10"
        result.append({
            "code": stage["code"],
            "name": stage["name"],
            "section": SECTION_NAMES.get(section_key, ""),
            "object_types": types,
            "observability": observability,
            "confirmation_method": method,
            "visual_class": stage["visual"],
            "note": stage.get("note", ""),
            "aliases": stage.get("aliases", []),
            "includes": list(dict.fromkeys(r["name"] for r in covered if r["name"] != stage["name"])),
            "source_rows": [{"row": r["row"], "code": r["code"] or f"{r['parent']} ·", "name": r["name"]}
                            for r in covered],
            "profile": profile,
        })
    result.sort(key=lambda item: min(row["row"] for row in item["source_rows"]))
    return {
        "version": VERSION,
        "source": SOURCE.name,
        "object_types": OBJECT_TYPES,
        "source_row_count": len(rows),
        "stages": result,
    }


def main() -> int:
    data = build()
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    counts = {k: sum(1 for s in data["stages"] if s["observability"] == k) for k in ("yes", "partial", "no")}
    print(f"{len(data['stages'])} этапов из {data['source_row_count']} строк Excel · наблюдаемость {counts}")
    return 0


